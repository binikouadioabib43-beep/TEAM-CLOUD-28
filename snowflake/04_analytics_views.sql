USE ROLE ECOABIDJAN_APP;
USE WAREHOUSE ECOABIDJAN_WH;
USE SCHEMA ECOABIDJAN.ANALYTICS;

-- Indicateurs globaux
CREATE OR REPLACE VIEW V_KPI_GLOBAL AS
SELECT
  (SELECT COUNT(*) FROM CORE.REPORTS)                                                    AS SIGNALEMENTS_TOTAL,
  (SELECT COUNT(*) FROM CORE.REPORTS WHERE STATUS IN ('SIGNALE','CONFIRME','PLANIFIE'))  AS SIGNALEMENTS_OUVERTS,
  (SELECT COUNT(*) FROM CORE.REPORTS WHERE STATUS = 'COLLECTE')                          AS SIGNALEMENTS_COLLECTES,
  (SELECT COALESCE(SUM(VALIDATED_WEIGHT_KG), 0) FROM CORE.DECLARATION_ITEMS)             AS KG_RECYCLES,
  (SELECT COALESCE(SUM(AMOUNT_FCFA), 0) FROM CORE.PAYMENTS WHERE STATUS = 'PAYEE')       AS FCFA_PAYES,
  (SELECT COALESCE(SUM(AMOUNT_FCFA), 0) FROM CORE.PAYMENTS WHERE STATUS = 'EN_ATTENTE')  AS FCFA_EN_ATTENTE,
  (SELECT COALESCE(SUM(POINTS), 0) FROM CORE.POINTS_TRANSACTIONS)                        AS POINTS_DISTRIBUES,
  (SELECT COUNT(*) FROM CORE.USERS WHERE ROLE IN ('citoyen','menage','commercant'))      AS USAGERS;

-- Tonnage recycle et remunerations par mois et par matiere
CREATE OR REPLACE VIEW V_RECYCLAGE_MENSUEL AS
SELECT
  DATE_TRUNC('MONTH', COALESCE(D.VALIDATED_AT, D.CREATED_AT)) AS MOIS,
  M.NAME                                                       AS MATIERE,
  SUM(I.VALIDATED_WEIGHT_KG)                                   AS KG_VALIDES,
  SUM(I.ESTIMATED_WEIGHT_KG)                                   AS KG_DECLARES,
  SUM(I.AMOUNT_FCFA)                                           AS FCFA_REMUNERES,
  COUNT(DISTINCT D.ID)                                         AS NB_DECLARATIONS
FROM CORE.DECLARATIONS D
JOIN CORE.DECLARATION_ITEMS I ON I.DECLARATION_ID = D.ID
JOIN CORE.MATERIALS M ON M.ID = I.MATERIAL_ID
WHERE D.STATUS = 'VALIDEE'
GROUP BY 1, 2;

-- Signalements par commune (avec densite pour 10 000 habitants)
CREATE OR REPLACE VIEW V_SIGNALEMENTS_COMMUNE AS
SELECT
  C.NAME AS COMMUNE,
  C.POPULATION,
  COUNT(R.ID)                                                          AS SIGNALEMENTS,
  COUNT_IF(R.STATUS IN ('SIGNALE','CONFIRME','PLANIFIE'))              AS OUVERTS,
  COUNT_IF(R.STATUS = 'COLLECTE')                                      AS COLLECTES,
  SUM(R.AI_ESTIMATED_WEIGHT_KG)                                        AS KG_ESTIMES_IA,
  ROUND(COUNT(R.ID) / NULLIF(C.POPULATION, 0) * 10000, 2)              AS SIGNALEMENTS_POUR_10K_HAB,
  AVG(IFF(R.STATUS = 'COLLECTE', DATEDIFF('hour', R.CREATED_AT, R.UPDATED_AT), NULL)) AS DELAI_MOYEN_COLLECTE_H
FROM CORE.COMMUNES C
LEFT JOIN CORE.REPORTS R ON R.COMMUNE_ID = C.ID
GROUP BY C.NAME, C.POPULATION;

-- Fiabilite de l'IA : estimation photo vs poids reellement collecte
CREATE OR REPLACE VIEW V_PRECISION_IA AS
SELECT
  A.PROVIDER,
  A.MODEL,
  A.PROMPT_VERSION,
  COUNT(*)                                                                         AS NB_COMPARAISONS,
  AVG(ABS(R.AI_ESTIMATED_WEIGHT_KG - R.VALIDATED_WEIGHT_KG) / R.VALIDATED_WEIGHT_KG) * 100 AS ERREUR_MOYENNE_PCT,
  AVG(A.CONFIDENCE)                                                                AS CONFIANCE_MOYENNE
FROM CORE.REPORTS R
JOIN CORE.AI_ANALYSES A ON A.REPORT_ID = R.ID
WHERE R.VALIDATED_WEIGHT_KG > 0 AND R.AI_ESTIMATED_WEIGHT_KG IS NOT NULL
GROUP BY 1, 2, 3;

-- Matieres detectees par l'IA (eclatement du JSON)
CREATE OR REPLACE VIEW V_MATIERES_DETECTEES_IA AS
SELECT
  A.ID                         AS ANALYSE_ID,
  A.REPORT_ID,
  R.COMMUNE_ID,
  F.VALUE:code::VARCHAR        AS MATIERE,
  F.VALUE:share::FLOAT         AS PART,
  F.VALUE:confidence::FLOAT    AS CONFIANCE,
  A.ESTIMATED_WEIGHT_KG * F.VALUE:share::FLOAT AS KG_ESTIMES,
  A.CREATED_AT
FROM CORE.AI_ANALYSES A
JOIN CORE.REPORTS R ON R.ID = A.REPORT_ID,
LATERAL FLATTEN(INPUT => TRY_PARSE_JSON(A.MATERIALS)) F;

-- Cout de collecte par tournee et par kg collecte
CREATE OR REPLACE VIEW V_COUT_COLLECTE AS
SELECT
  C.ID AS TOURNEE_ID,
  C.NAME,
  C.PLANNED_DATE,
  C.TOTAL_DISTANCE_KM,
  C.ESTIMATED_COST_FCFA,
  COALESCE(K.COUT_REEL, 0)                                              AS COUT_REEL_FCFA,
  COALESCE(S.KG_COLLECTES, 0)                                           AS KG_COLLECTES,
  COALESCE(K.COUT_REEL, C.ESTIMATED_COST_FCFA) / NULLIF(S.KG_COLLECTES, 0) AS FCFA_PAR_KG
FROM CORE.COLLECTIONS C
LEFT JOIN (SELECT COLLECTION_ID, SUM(AMOUNT_FCFA) AS COUT_REEL FROM CORE.COLLECTION_COSTS GROUP BY 1) K
  ON K.COLLECTION_ID = C.ID
LEFT JOIN (SELECT COLLECTION_ID, SUM(COLLECTED_WEIGHT_KG) AS KG_COLLECTES FROM CORE.COLLECTION_STOPS GROUP BY 1) S
  ON S.COLLECTION_ID = C.ID;

-- Classement des usagers (points et remunerations)
CREATE OR REPLACE VIEW V_CLASSEMENT_USAGERS AS
SELECT
  U.ID, U.FULL_NAME, U.ROLE, CM.NAME AS COMMUNE, U.POINTS_BALANCE,
  COALESCE(SUM(P.AMOUNT_FCFA), 0) AS FCFA_GAGNES
FROM CORE.USERS U
LEFT JOIN CORE.COMMUNES CM ON CM.ID = U.COMMUNE_ID
LEFT JOIN CORE.PAYMENTS P ON P.USER_ID = U.ID AND P.STATUS <> 'ANNULEE'
WHERE U.ROLE IN ('citoyen','menage','commercant')
GROUP BY 1, 2, 3, 4, 5;

-- Zones prioritaires : grille d'environ 1 km avec les signalements encore ouverts
CREATE OR REPLACE VIEW V_ZONES_PRIORITAIRES AS
SELECT
  ROUND(LATITUDE, 2)  AS LAT_CELLULE,
  ROUND(LONGITUDE, 2) AS LON_CELLULE,
  COUNT(*)            AS SIGNALEMENTS_OUVERTS,
  SUM(AI_ESTIMATED_WEIGHT_KG) AS KG_ESTIMES
FROM CORE.REPORTS
WHERE STATUS IN ('SIGNALE','CONFIRME','PLANIFIE')
GROUP BY 1, 2
ORDER BY SIGNALEMENTS_OUVERTS DESC;
