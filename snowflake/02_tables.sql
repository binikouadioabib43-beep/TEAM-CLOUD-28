-- =============================================================================
-- EcoAbidjan - 02 : Tables du schema CORE
-- Miroir des tables operationnelles (PostgreSQL). Alimentees par le backend
-- (POST /api/admin/snowflake/sync). Les donnees personnelles sensibles
-- (e-mail, telephone, mot de passe) ne sont PAS repliquees.
-- Dans Snowflake, les cles primaires/etrangeres sont declaratives (non appliquees).
-- CREATE OR REPLACE : CORE est une copie integrale rechargee a chaque synchronisation.
-- =============================================================================

USE ROLE ECOABIDJAN_APP;
USE WAREHOUSE ECOABIDJAN_WH;
USE SCHEMA ECOABIDJAN.CORE;

CREATE OR REPLACE TABLE COMMUNES (
  ID NUMBER PRIMARY KEY,
  NAME VARCHAR(80),
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  POPULATION NUMBER,
  IS_PILOT BOOLEAN                  -- commune du projet pilote
);

CREATE OR REPLACE TABLE USERS (
  ID NUMBER PRIMARY KEY,
  FULL_NAME VARCHAR(120),
  ROLE VARCHAR(20),                 -- citoyen | menage | commercant | agent | admin
  COMMUNE_ID NUMBER REFERENCES COMMUNES(ID),
  HOUSEHOLD_SIZE NUMBER,
  BUSINESS_NAME VARCHAR(120),
  BUSINESS_TYPE VARCHAR(80),
  POINTS_BALANCE NUMBER,
  IS_ACTIVE BOOLEAN,
  CREATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE MATERIALS (
  ID NUMBER PRIMARY KEY,
  CODE VARCHAR(30),
  NAME VARCHAR(80),
  DESCRIPTION VARCHAR,
  IS_RECYCLABLE BOOLEAN,
  IS_ACTIVE BOOLEAN
);

-- Historique des tarifs : le tarif en vigueur a VALID_TO NULL
CREATE OR REPLACE TABLE TARIFFS (
  ID NUMBER PRIMARY KEY,
  MATERIAL_ID NUMBER REFERENCES MATERIALS(ID),
  PRICE_FCFA_PER_KG NUMBER,
  VALID_FROM TIMESTAMP_NTZ,
  VALID_TO TIMESTAMP_NTZ,
  CREATED_BY NUMBER,
  NOTE VARCHAR(255)
);

CREATE OR REPLACE TABLE PARAMETERS (
  KEY VARCHAR(60) PRIMARY KEY,
  VALUE VARCHAR(255),
  DESCRIPTION VARCHAR(255),
  UPDATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE RELAY_POINTS (
  ID NUMBER PRIMARY KEY,
  NAME VARCHAR(120),
  COMMUNE_ID NUMBER REFERENCES COMMUNES(ID),
  ADDRESS VARCHAR(255),
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  ACCEPTED_MATERIALS VARCHAR(255),
  OPENING_HOURS VARCHAR(120),
  CAPACITY_KG FLOAT,
  IS_ACTIVE BOOLEAN
);

CREATE OR REPLACE TABLE COLLECTIONS (
  ID NUMBER PRIMARY KEY,
  NAME VARCHAR(120),
  PLANNED_DATE DATE,
  DEPOT_LABEL VARCHAR(120),
  DEPOT_LATITUDE FLOAT,
  DEPOT_LONGITUDE FLOAT,
  VEHICLE_TYPE VARCHAR(40),
  STATUS VARCHAR(20),
  TOTAL_DISTANCE_KM FLOAT,
  ESTIMATED_DURATION_MIN FLOAT,
  ESTIMATED_COST_FCFA NUMBER,
  CREATED_BY NUMBER,
  CREATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE REPORTS (
  ID NUMBER PRIMARY KEY,
  USER_ID NUMBER REFERENCES USERS(ID),
  COMMUNE_ID NUMBER REFERENCES COMMUNES(ID),
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  ADDRESS VARCHAR(255),
  DESCRIPTION VARCHAR,
  STATUS VARCHAR(20),               -- SIGNALE | CONFIRME | PLANIFIE | COLLECTE | REJETE
  AI_ESTIMATED_WEIGHT_KG FLOAT,     -- estimation indicative de l'IA
  VALIDATED_WEIGHT_KG FLOAT,        -- poids reellement collecte
  POINTS_AWARDED NUMBER,
  COLLECTION_ID NUMBER REFERENCES COLLECTIONS(ID),
  CREATED_AT TIMESTAMP_NTZ,
  UPDATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DECLARATIONS (
  ID NUMBER PRIMARY KEY,
  USER_ID NUMBER REFERENCES USERS(ID),
  MODE VARCHAR(20),                 -- POINT_RELAIS | COLLECTE_DOMICILE
  RELAY_POINT_ID NUMBER REFERENCES RELAY_POINTS(ID),
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  STATUS VARCHAR(20),               -- SOUMISE | PLANIFIEE | VALIDEE | REJETEE
  NOTE VARCHAR,
  TOTAL_ESTIMATED_KG FLOAT,
  TOTAL_VALIDATED_KG FLOAT,
  TOTAL_AMOUNT_FCFA NUMBER,
  POINTS_AWARDED NUMBER,
  VALIDATED_BY NUMBER,
  VALIDATED_AT TIMESTAMP_NTZ,
  REJECTION_REASON VARCHAR(255),
  COLLECTION_ID NUMBER REFERENCES COLLECTIONS(ID),
  CREATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE PHOTOS (
  ID NUMBER PRIMARY KEY,
  REPORT_ID NUMBER REFERENCES REPORTS(ID),
  DECLARATION_ID NUMBER REFERENCES DECLARATIONS(ID),
  FILE_PATH VARCHAR(255),
  ORIGINAL_NAME VARCHAR(255),
  CONTENT_TYPE VARCHAR(60),
  SIZE_BYTES NUMBER,
  SHA256 VARCHAR(64),
  UPLOADED_AT TIMESTAMP_NTZ
);

-- Tracabilite des analyses IA : fournisseur, modele, version du prompt, reponse brute
CREATE OR REPLACE TABLE AI_ANALYSES (
  ID NUMBER PRIMARY KEY,
  PHOTO_ID NUMBER REFERENCES PHOTOS(ID),
  REPORT_ID NUMBER REFERENCES REPORTS(ID),
  PROVIDER VARCHAR(30),
  MODEL VARCHAR(80),
  PROMPT_VERSION VARCHAR(20),
  MATERIALS VARCHAR,                -- JSON : [{"code","share","confidence"}] ; lire avec PARSE_JSON
  ESTIMATED_WEIGHT_KG FLOAT,
  ESTIMATED_VOLUME_M3 FLOAT,
  CONFIDENCE FLOAT,
  SUMMARY VARCHAR,
  RAW_RESPONSE VARCHAR,
  STATUS VARCHAR(20),
  ERROR VARCHAR,
  DURATION_MS NUMBER,
  CREATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE DECLARATION_ITEMS (
  ID NUMBER PRIMARY KEY,
  DECLARATION_ID NUMBER REFERENCES DECLARATIONS(ID),
  MATERIAL_ID NUMBER REFERENCES MATERIALS(ID),
  ESTIMATED_WEIGHT_KG FLOAT,        -- declare par l'usager
  VALIDATED_WEIGHT_KG FLOAT,        -- pese par l'agent
  TARIFF_ID NUMBER REFERENCES TARIFFS(ID),
  UNIT_PRICE_FCFA NUMBER,           -- tarif applique (fige au moment de la validation)
  AMOUNT_FCFA NUMBER
);

CREATE OR REPLACE TABLE PAYMENTS (
  ID NUMBER PRIMARY KEY,
  USER_ID NUMBER REFERENCES USERS(ID),
  KIND VARCHAR(20),                 -- REMUNERATION | CONVERSION_POINTS
  DECLARATION_ID NUMBER REFERENCES DECLARATIONS(ID),
  POINTS_CONVERTED NUMBER,
  AMOUNT_FCFA NUMBER,
  STATUS VARCHAR(20),               -- EN_ATTENTE | PAYEE | ANNULEE
  METHOD VARCHAR(30),
  REFERENCE VARCHAR(80),
  CREATED_AT TIMESTAMP_NTZ,
  PAID_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE POINTS_TRANSACTIONS (
  ID NUMBER PRIMARY KEY,
  USER_ID NUMBER REFERENCES USERS(ID),
  POINTS NUMBER,
  REASON VARCHAR(120),
  DECLARATION_ID NUMBER,
  REPORT_ID NUMBER,
  CREATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE COLLECTION_STOPS (
  ID NUMBER PRIMARY KEY,
  COLLECTION_ID NUMBER REFERENCES COLLECTIONS(ID),
  SEQUENCE NUMBER,
  STOP_TYPE VARCHAR(20),
  REPORT_ID NUMBER,
  DECLARATION_ID NUMBER,
  LATITUDE FLOAT,
  LONGITUDE FLOAT,
  DISTANCE_FROM_PREVIOUS_KM FLOAT,
  STATUS VARCHAR(20),
  COLLECTED_WEIGHT_KG FLOAT
);

CREATE OR REPLACE TABLE COLLECTION_COSTS (
  ID NUMBER PRIMARY KEY,
  COLLECTION_ID NUMBER REFERENCES COLLECTIONS(ID),
  COST_TYPE VARCHAR(30),            -- CARBURANT | MAIN_OEUVRE | VEHICULE | AUTRE
  AMOUNT_FCFA NUMBER,
  NOTE VARCHAR(255),
  CREATED_AT TIMESTAMP_NTZ
);

-- Conversations avec l'assistant Eco (analyse des besoins des usagers)
CREATE OR REPLACE TABLE CHAT_MESSAGES (
  ID NUMBER PRIMARY KEY,
  SESSION_ID VARCHAR(64),
  USER_ID NUMBER REFERENCES USERS(ID),
  ROLE VARCHAR(12),                 -- user | assistant
  CONTENT VARCHAR,
  INTENT VARCHAR(40),               -- intention detectee (tarifs, relais, estimation...)
  PROVIDER VARCHAR(30),             -- local | snowflake-cortex
  MODEL VARCHAR(80),
  LATENCY_MS NUMBER,
  ERROR VARCHAR,
  CREATED_AT TIMESTAMP_NTZ
);

-- Resultats bruts des analyses d'images faites directement dans Snowflake (05_cortex_image_analysis.sql)
CREATE TABLE IF NOT EXISTS ECOABIDJAN.RAW.AI_BATCH_RESULTS (
  RELATIVE_PATH VARCHAR,
  MODEL VARCHAR(80),
  PROMPT_VERSION VARCHAR(20),
  RESPONSE VARCHAR,
  ANALYZED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
