-- EcoAbidjan - 06 : Simulation du projet pilote DANS Snowflake
-- Donnees synthetiques generees avec GENERATOR, positions en GEOGRAPHY.
--   - 4 communes pilotes : Yopougon, Abobo, Cocody, Koumassi
--   - 500 menages et 200 commercants repartis selon le poids des communes
--   - 13 semaines de declarations, seuil Y, remuneration et points
-- Duree : quelques secondes sur un entrepot XSMALL.
-- =============================================================================

USE ROLE ECOABIDJAN_APP;          -- ou ACCOUNTADMIN sur un compte d'essai
USE WAREHOUSE ECOABIDJAN_WH;      -- ou COMPUTE_WH
CREATE SCHEMA IF NOT EXISTS ECOABIDJAN.SIM COMMENT = 'Simulation du projet pilote (donnees synthetiques)';
USE SCHEMA ECOABIDJAN.SIM;

-- 1. Regles metier de la simulation (memes valeurs que l'application)
CREATE OR REPLACE TABLE PARAMETRES AS
SELECT
  10::FLOAT  AS SEUIL_Y_KG,            -- poids minimum pour une collecte a domicile
  10         AS POINTS_PAR_KG,         -- points par kg valide en point relais
  20         AS BONUS_DEPOT,           -- bonus par depot en point relais
  1::FLOAT   AS POINT_VALEUR_FCFA,     -- conversion : 1 point = 1 FCFA
  500        AS POINTS_MIN_CONVERSION,
  200        AS TARIF_CARTON,          -- FCFA/kg
  250        AS TARIF_PLASTIQUE,
  300        AS TARIF_ALUMINIUM;

-- 2. Communes pilotes : poids dans l'echantillon (proche de la population) et centre geographique
CREATE OR REPLACE TABLE COMMUNES_PILOTES (COMMUNE VARCHAR, POIDS FLOAT, BORNE_MIN FLOAT, BORNE_MAX FLOAT, CENTRE GEOGRAPHY) AS
SELECT column1, column2, column3, column4, ST_MAKEPOINT(column6, column5)
FROM VALUES
  ('Yopougon', 0.36, 0.00, 0.36, 5.3450, -4.0750),
  ('Abobo',    0.26, 0.36, 0.62, 5.4167, -4.0167),
  ('Cocody',   0.20, 0.62, 0.82, 5.3600, -3.9700),
  ('Koumassi', 0.18, 0.82, 1.00, 5.2900, -3.9500);

-- 3. Points relais (2 par commune pilote)
CREATE OR REPLACE TABLE POINTS_RELAIS (NOM VARCHAR, COMMUNE VARCHAR, POSITION GEOGRAPHY) AS
SELECT column1, column2, ST_MAKEPOINT(column4, column3)
FROM VALUES
  ('Point Relais Cocody Angre', 'Cocody', 5.3950, -3.9900),
  ('Point Relais Cocody Riviera 2', 'Cocody', 5.3480, -3.9600),
  ('Point Relais Yopougon Siporex', 'Yopougon', 5.3400, -4.0830),
  ('Point Relais Yopougon Niangon', 'Yopougon', 5.3250, -4.1000),
  ('Point Relais Abobo Gare', 'Abobo', 5.4210, -4.0200),
  ('Point Relais Abobo PK18', 'Abobo', 5.4420, -4.0350),
  ('Point Relais Koumassi Remblais', 'Koumassi', 5.2950, -3.9450),
  ('Point Relais Koumassi Grand Marche', 'Koumassi', 5.2880, -3.9560);

-- 4. 500 menages (GENERATOR) ---------------------------------------------------
CREATE OR REPLACE TABLE MENAGES AS
WITH G AS (
  SELECT
    ROW_NUMBER() OVER (ORDER BY SEQ4())            AS N,
    UNIFORM(0::FLOAT, 1::FLOAT, RANDOM())          AS U,
    UNIFORM(-0.018::FLOAT, 0.018::FLOAT, RANDOM()) AS DLAT,
    UNIFORM(-0.018::FLOAT, 0.018::FLOAT, RANDOM()) AS DLON,
    UNIFORM(2, 10, RANDOM())                       AS TAILLE_FOYER,
    UNIFORM(0::FLOAT, 1::FLOAT, RANDOM()) < 0.78   AS ACTIF
  FROM TABLE(GENERATOR(ROWCOUNT => 500))
)
SELECT
  'M' || LPAD(G.N, 4, '0') AS MENAGE_ID,
  C.COMMUNE,
  G.TAILLE_FOYER,
  G.ACTIF,
  ST_MAKEPOINT(ST_X(C.CENTRE) + G.DLON, ST_Y(C.CENTRE) + G.DLAT) AS POSITION
FROM G
JOIN COMMUNES_PILOTES C ON G.U >= C.BORNE_MIN AND (G.U < C.BORNE_MAX OR C.BORNE_MAX = 1);

-- 5. 200 commercants (GENERATOR) ------------------------------------------------
CREATE OR REPLACE TABLE COMMERCANTS AS
WITH G AS (
  SELECT
    ROW_NUMBER() OVER (ORDER BY SEQ4())            AS N,
    UNIFORM(0::FLOAT, 1::FLOAT, RANDOM())          AS U,
    UNIFORM(0::FLOAT, 1::FLOAT, RANDOM())          AS T,
    UNIFORM(-0.018::FLOAT, 0.018::FLOAT, RANDOM()) AS DLAT,
    UNIFORM(-0.018::FLOAT, 0.018::FLOAT, RANDOM()) AS DLON,
    UNIFORM(0::FLOAT, 1::FLOAT, RANDOM()) < 0.88   AS ACTIF
  FROM TABLE(GENERATOR(ROWCOUNT => 200))
)
SELECT
  'C' || LPAD(G.N, 4, '0') AS COMMERCANT_ID,
  C.COMMUNE,
  CASE WHEN G.T < 0.30 THEN 'Maquis / restaurant'
       WHEN G.T < 0.60 THEN 'Boutique / epicerie'
       WHEN G.T < 0.68 THEN 'Supermarche'
       WHEN G.T < 0.90 THEN 'Commerce du marche'
       ELSE 'Bar / buvette' END AS TYPE_COMMERCE,
  CASE WHEN G.T < 0.30 THEN 1.0 WHEN G.T < 0.60 THEN 0.8 WHEN G.T < 0.68 THEN 3.0
       WHEN G.T < 0.90 THEN 1.2 ELSE 1.1 END AS MULTIPLICATEUR_VOLUME,
  G.ACTIF,
  ST_MAKEPOINT(ST_X(C.CENTRE) + G.DLON, ST_Y(C.CENTRE) + G.DLAT) AS POSITION
FROM G
JOIN COMMUNES_PILOTES C ON G.U >= C.BORNE_MIN AND (G.U < C.BORNE_MAX OR C.BORNE_MAX = 1);

-- 6. Declarations brutes : 13 semaines x usagers actifs (valeurs aleatoires figees dans une table)
CREATE OR REPLACE TABLE DECLARATIONS_BRUTES AS
SELECT
  'MENAGE' AS PROFIL, M.MENAGE_ID AS USAGER_ID, M.COMMUNE, M.POSITION, S.SEMAINE,
  UNIFORM(1.5::FLOAT, 6.0::FLOAT, RANDOM()) * POWER(M.TAILLE_FOYER / 4, 0.7) AS KG_TOTAL,
  0.50 * UNIFORM(0.6::FLOAT, 1.4::FLOAT, RANDOM()) AS PART_PLASTIQUE,
  0.35 * UNIFORM(0.6::FLOAT, 1.4::FLOAT, RANDOM()) AS PART_CARTON,
  0.15 * UNIFORM(0.6::FLOAT, 1.4::FLOAT, RANDOM()) AS PART_ALUMINIUM,
  UNIFORM(0::FLOAT, 1::FLOAT, RANDOM()) < 0.45 AS SOUHAITE_DOMICILE,
  UNIFORM(0.82::FLOAT, 1.05::FLOAT, RANDOM()) AS RATIO_PESEE,
  UNIFORM(0::FLOAT, 1::FLOAT, RANDOM()) AS TIRAGE_PARTICIPATION
FROM MENAGES M
CROSS JOIN (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS SEMAINE FROM TABLE(GENERATOR(ROWCOUNT => 13))) S
WHERE M.ACTIF
UNION ALL
SELECT
  'COMMERCANT', C.COMMERCANT_ID, C.COMMUNE, C.POSITION, S.SEMAINE,
  UNIFORM(8::FLOAT, 25::FLOAT, RANDOM()) * C.MULTIPLICATEUR_VOLUME,
  0.45 * UNIFORM(0.6::FLOAT, 1.4::FLOAT, RANDOM()),
  0.40 * UNIFORM(0.6::FLOAT, 1.4::FLOAT, RANDOM()),
  0.15 * UNIFORM(0.6::FLOAT, 1.4::FLOAT, RANDOM()),
  UNIFORM(0::FLOAT, 1::FLOAT, RANDOM()) < 0.65,
  UNIFORM(0.82::FLOAT, 1.05::FLOAT, RANDOM()),
  UNIFORM(0::FLOAT, 1::FLOAT, RANDOM())
FROM COMMERCANTS C
CROSS JOIN (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS SEMAINE FROM TABLE(GENERATOR(ROWCOUNT => 13))) S
WHERE C.ACTIF;

-- 7. Declarations : application du seuil Y, pesee, remuneration et points
CREATE OR REPLACE TEMPORARY TABLE DECL_CALC AS
WITH B AS (
  SELECT D.*, P.*,
         D.PART_PLASTIQUE + D.PART_CARTON + D.PART_ALUMINIUM AS PART_TOTALE
  FROM DECLARATIONS_BRUTES D CROSS JOIN PARAMETRES P
  -- participation hebdomadaire : 55 % des semaines pour un menage actif, 85 % pour un commercant
  WHERE D.TIRAGE_PARTICIPATION < IFF(D.PROFIL = 'MENAGE', 0.55, 0.85)
),
K AS (
  SELECT B.*,
    ROUND(B.KG_TOTAL * B.PART_PLASTIQUE / B.PART_TOTALE, 1) AS KG_PLASTIQUE,
    ROUND(B.KG_TOTAL * B.PART_CARTON / B.PART_TOTALE, 1)    AS KG_CARTON,
    ROUND(B.KG_TOTAL * B.PART_ALUMINIUM / B.PART_TOTALE, 1) AS KG_ALUMINIUM,
    -- Seuil Y : sous Y kg, la collecte a domicile est refusee -> point relais
    IFF(B.SOUHAITE_DOMICILE AND B.KG_TOTAL >= B.SEUIL_Y_KG, 'COLLECTE_DOMICILE', 'POINT_RELAIS') AS MODE,
    B.SOUHAITE_DOMICILE AND B.KG_TOTAL < B.SEUIL_Y_KG AS ORIENTE_PAR_SEUIL_Y
  FROM B
)
SELECT
  UUID_STRING() AS DECLARATION_ID, PROFIL, USAGER_ID, COMMUNE, SEMAINE,
  DATEADD('week', SEMAINE - 14, CURRENT_DATE()) AS DATE_DECLARATION,
  MODE, ORIENTE_PAR_SEUIL_Y, POSITION,
  KG_PLASTIQUE, KG_CARTON, KG_ALUMINIUM,
  KG_PLASTIQUE + KG_CARTON + KG_ALUMINIUM AS KG_DECLARES,
  ROUND((KG_PLASTIQUE + KG_CARTON + KG_ALUMINIUM) * RATIO_PESEE, 1) AS KG_VALIDES,
  ROUND(RATIO_PESEE * (KG_PLASTIQUE * TARIF_PLASTIQUE + KG_CARTON * TARIF_CARTON + KG_ALUMINIUM * TARIF_ALUMINIUM)) AS REMUNERATION_FCFA,
  IFF(MODE = 'POINT_RELAIS',
      FLOOR((KG_PLASTIQUE + KG_CARTON + KG_ALUMINIUM) * RATIO_PESEE * POINTS_PAR_KG) + BONUS_DEPOT, 0) AS POINTS
FROM K;

-- Point relais le plus proche (ST_DISTANCE sur GEOGRAPHY, en metres)
CREATE OR REPLACE TABLE DECLARATIONS AS
SELECT D.*,
       IFF(D.MODE = 'POINT_RELAIS', R.NOM, NULL) AS POINT_RELAIS,
       ROUND(ST_DISTANCE(D.POSITION, R.POSITION)) AS DISTANCE_POINT_RELAIS_M
FROM DECL_CALC D
JOIN POINTS_RELAIS R ON R.COMMUNE = D.COMMUNE
QUALIFY ROW_NUMBER() OVER (PARTITION BY D.DECLARATION_ID ORDER BY ST_DISTANCE(D.POSITION, R.POSITION)) = 1;

-- 8. Resultats ------------------------------------------------------------------

-- Synthese par commune (a mettre dans les planches)
CREATE OR REPLACE VIEW V_SYNTHESE_COMMUNE AS
WITH M AS (SELECT COMMUNE, COUNT(*) AS N FROM MENAGES GROUP BY COMMUNE),
     X AS (SELECT COMMUNE, COUNT(*) AS N FROM COMMERCANTS GROUP BY COMMUNE),
     D AS (
       SELECT COMMUNE,
              COUNT(*)                                        AS DECLARATIONS,
              ROUND(SUM(KG_VALIDES), 0)                       AS KG_VALIDES,
              SUM(REMUNERATION_FCFA)                          AS REMUNERATION_FCFA,
              SUM(POINTS)                                     AS POINTS,
              ROUND(COUNT_IF(MODE = 'POINT_RELAIS') / COUNT(*) * 100, 1) AS PART_POINT_RELAIS_PCT,
              COUNT_IF(ORIENTE_PAR_SEUIL_Y)                   AS ORIENTES_PAR_SEUIL_Y
       FROM DECLARATIONS GROUP BY COMMUNE)
SELECT C.COMMUNE, COALESCE(M.N, 0) AS MENAGES, COALESCE(X.N, 0) AS COMMERCANTS,
       D.DECLARATIONS, D.KG_VALIDES, D.REMUNERATION_FCFA, D.POINTS, D.PART_POINT_RELAIS_PCT, D.ORIENTES_PAR_SEUIL_Y
FROM COMMUNES_PILOTES C
LEFT JOIN M ON M.COMMUNE = C.COMMUNE
LEFT JOIN X ON X.COMMUNE = C.COMMUNE
LEFT JOIN D ON D.COMMUNE = C.COMMUNE;

-- Effet du seuil Y : combien d'apports sont orientes vers les points relais selon la valeur de Y
CREATE OR REPLACE VIEW V_SENSIBILITE_SEUIL_Y AS
SELECT
  Y.VALEUR AS SEUIL_Y_KG,
  COUNT_IF(D.SOUHAITE_DOMICILE AND D.KG_TOTAL >= Y.VALEUR) AS ARRETS_DOMICILE,
  COUNT_IF(D.SOUHAITE_DOMICILE AND D.KG_TOTAL < Y.VALEUR)  AS ORIENTES_POINT_RELAIS,
  ROUND(AVG(IFF(D.SOUHAITE_DOMICILE AND D.KG_TOTAL >= Y.VALEUR, D.KG_TOTAL, NULL)), 1) AS KG_MOYEN_PAR_ARRET,
  -- cout logistique par kg collecte a domicile (arret = 500 FCFA main d'oeuvre + 300 FCFA de detour)
  ROUND(800 / NULLIF(AVG(IFF(D.SOUHAITE_DOMICILE AND D.KG_TOTAL >= Y.VALEUR, D.KG_TOTAL, NULL)), 0), 0) AS COUT_FCFA_PAR_KG
FROM DECLARATIONS_BRUTES D
CROSS JOIN (SELECT column1 AS VALEUR FROM VALUES (0), (5), (10), (15), (20)) Y
GROUP BY Y.VALEUR
ORDER BY Y.VALEUR;

-- Revenu mensuel moyen par profil
CREATE OR REPLACE VIEW V_REVENU_MENSUEL AS
SELECT PROFIL,
       COUNT(DISTINCT USAGER_ID) AS USAGERS_ACTIFS,
       ROUND(SUM(REMUNERATION_FCFA) / COUNT(DISTINCT USAGER_ID) / 3, 0) AS REVENU_MENSUEL_MOYEN_FCFA,
       ROUND(SUM(POINTS) / COUNT(DISTINCT USAGER_ID) / 3, 0)            AS POINTS_MENSUELS_MOYENS
FROM DECLARATIONS
GROUP BY PROFIL;

-- Distance moyenne au point relais le plus proche (fonctions geographiques)
CREATE OR REPLACE VIEW V_ACCESSIBILITE_POINTS_RELAIS AS
WITH PROCHE AS (
  SELECT M.MENAGE_ID, M.COMMUNE, MIN(ST_DISTANCE(M.POSITION, R.POSITION)) AS DIST_M
  FROM MENAGES M CROSS JOIN POINTS_RELAIS R
  GROUP BY M.MENAGE_ID, M.COMMUNE
)
SELECT COMMUNE,
       ROUND(AVG(DIST_M) / 1000, 2) AS DISTANCE_MOYENNE_KM,
       COUNT_IF(DIST_M <= 1500)     AS MENAGES_A_MOINS_DE_1_5_KM,
       COUNT(*)                     AS MENAGES
FROM PROCHE
GROUP BY COMMUNE;

-- Controles des contraintes du hackathon
SELECT 'Communes pilotes' AS CONTROLE, COUNT(*) AS VALEUR, COUNT(*) >= 4 AS OK FROM COMMUNES_PILOTES
UNION ALL SELECT 'Menages', COUNT(*), COUNT(*) >= 500 FROM MENAGES
UNION ALL SELECT 'Commercants', COUNT(*), COUNT(*) >= 200 FROM COMMERCANTS;

SELECT * FROM V_SYNTHESE_COMMUNE ORDER BY MENAGES DESC;
SELECT * FROM V_SENSIBILITE_SEUIL_Y;
SELECT * FROM V_REVENU_MENSUEL;
